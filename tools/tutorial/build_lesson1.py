def prompt_blocks(steps):
    blocks = list(PREAMBLE)
    blocks.append(("h2", "The lesson, step by step"))
    for number, step, beats in steps:
        blocks.append(("h3", f"Step {number}. {step.title}  ({step.id})"))
        for letter, beat, pages in beats:
            is_move = isinstance(beat, src.Move)
            label = f"Step {number}{letter}"
            kind = "Move" if is_move else "Note"
            if len(beats) > 1 or is_move:
                blocks.append(("h4", f"{label}: {kind}" + (f" ({beat.key})" if is_move else "")))
            for index, page in enumerate(pages, 1):
                last = index == len(pages)
                if is_move and last:
                    blocks.append(("page", f"Page {index} of {len(pages)} (shown with the \"To continue\" block)", page))
                else:
                    button = beat.button if (not is_move and last) else "Continue"
                    blocks.append(("page", f"Page {index} of {len(pages)}", page, f"[{button}]"))
            if is_move:
                blocks.append(("player", beat.instruction))
            for note in getattr(beat, "build", []):
                blocks.append(("build", note))
            if not is_move and beat.engine:
                blocks.append(("engine", beat.engine))
    blocks.append(("h2", "Checks the build must pass"))
    for item in [
        "bash tools/check.sh --skip-client, including the tutorial tests (dotnet run --project tests/L5R.Core.Tests -- --filter tutorial): the whole lesson plays through using only what each step offers.",
        "bash tools/check-tutorial.sh: the lesson played through the real table controls, ending with a mid-lesson exit through the table menu.",
        "python3 tools/tutorial/build_lesson1.py --check: this document and the game's text are generated from the same source.",
        "Every page is at most %d characters; every number the text quotes is checked against the catalogue." % LIMIT,
    ]:
        blocks.append(("b", item))
    return blocks


def to_markdown(blocks) -> str:
    out = []
    for block in blocks:
        kind = block[0]
        if kind == "h1": out.append(f"# {block[1]}\n")
        elif kind == "h2": out.append(f"\n## {block[1]}\n")
        elif kind == "h3": out.append(f"\n### {block[1]}\n")
        elif kind == "h4": out.append(f"\n#### {block[1]}\n")
        elif kind == "p": out.append(block[1] + "\n")
        elif kind == "b": out.append(f"- {block[1]}")
        elif kind == "page":
            quoted = "\n".join(("> " + line).rstrip() for line in block[2].split("\n"))
            out.append(f"\n**{block[1]}**\n\n{quoted}\n" + (f"\n{block[3]}\n" if len(block) > 3 else ""))
        elif kind == "player": out.append(f"**Player must:** {block[1]}\n")
        elif kind == "build": out.append(f"*Build:* {block[1]}\n")
        elif kind == "engine": out.append(f"*Engine:* {block[1]}\n")
    return "\n".join(out).replace("\n\n\n", "\n\n") + "\n"


def to_docx(blocks, path: Path) -> bool:
    try:
        import docx
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.oxml.ns import qn
        from docx.oxml import OxmlElement
        from docx.shared import Pt, RGBColor, Inches
    except ImportError:
        return False
    doc = docx.Document()
    section = doc.sections[0]
    section.left_margin = section.right_margin = Inches(1)
    normal = doc.styles["Normal"]; normal.font.name = "Calibri"; normal.font.size = Pt(11)
    for name, size in (("Heading 1", 22), ("Heading 2", 16), ("Heading 3", 13), ("Heading 4", 11.5)):
        style = doc.styles[name]; style.font.name = "Calibri"; style.font.size = Pt(size); style.font.color.rgb = RGBColor(0x5A, 0x3A, 0x12)

    def shade(cell_or_par, fill):
        element = cell_or_par._element.get_or_add_pPr() if hasattr(cell_or_par._element, "get_or_add_pPr") else cell_or_par._element
        shd = OxmlElement("w:shd"); shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto"); shd.set(qn("w:fill"), fill); element.append(shd)

    def labelled(label, text, color):
        paragraph = doc.add_paragraph()
        run = paragraph.add_run(label + " "); run.bold = True; run.font.color.rgb = color
        paragraph.add_run(text)
        paragraph.paragraph_format.space_after = Pt(4)

    for block in blocks:
        kind = block[0]
        if kind == "h1": doc.add_heading(block[1], 0)
        elif kind == "h2": doc.add_heading(block[1], 1)
        elif kind == "h3": doc.add_heading(block[1], 2)
        elif kind == "h4": doc.add_heading(block[1], 3)
        elif kind == "p": doc.add_paragraph(block[1])
        elif kind == "b": doc.add_paragraph(block[1], style="List Bullet")
        elif kind == "page":
            head = doc.add_paragraph(); run = head.add_run(block[1]); run.bold = True; run.font.size = Pt(9.5); run.font.color.rgb = RGBColor(0x77, 0x77, 0x77)
            head.paragraph_format.space_after = Pt(0); head.paragraph_format.keep_with_next = True
            for index, line in enumerate(block[2].split("\n")):
                if not line.strip():
                    continue
                paragraph = doc.add_paragraph(line); paragraph.paragraph_format.left_indent = Inches(0.3); paragraph.paragraph_format.space_after = Pt(3)
                shade(paragraph, "F4EFE3")
            if len(block) > 3:
                button = doc.add_paragraph(); button.paragraph_format.left_indent = Inches(0.3)
                run = button.add_run(block[3]); run.bold = True; run.font.color.rgb = RGBColor(0x8A, 0x5A, 0x00)
        elif kind == "player": labelled("Player must:", block[1], RGBColor(0xA0, 0x1E, 0x1E))
        elif kind == "build": labelled("Build:", block[1], RGBColor(0x1F, 0x4E, 0x79))
        elif kind == "engine": labelled("Engine:", block[1], RGBColor(0x2E, 0x6B, 0x3A))
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(path)
    return True


def main() -> int:
    check = "--check" in sys.argv
    steps = expand()
    blocks = prompt_blocks(steps)
    outputs = {MD: to_markdown(blocks), CS: build_cs(steps)}
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_bytes().decode("utf-8") != text]
    if check:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)} (run python3 tools/tutorial/build_lesson1.py)")
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(text.encode("utf-8"))
    if "--no-docx" not in sys.argv:
        print("docx:", "written" if to_docx(blocks, DOCX) else "skipped (python-docx not installed)")
    print(f"{len(steps)} steps, {sum(len(p) for _, _, bs in steps for _, _, p in bs)} pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
