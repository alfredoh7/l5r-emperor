# ---- paging -------------------------------------------------------------------------------------------------------------------------------------------------------------

def sentences(paragraph: str) -> list[str]:
    parts = re.split(r'(?<=[.!?])\s+(?=[A-Z"(0-9])', paragraph.strip())
    return [p for p in parts if p]


def page_text(text: str) -> list[str]:
    """Splits a beat's text into note-column pages: a line of --- forces a break; otherwise paragraphs are packed up to LIMIT characters, and a paragraph longer than
    LIMIT is split at sentence boundaries (never inside a sentence)."""
    pages: list[str] = []
    for block in re.split(r"\n---\n", text.strip()):
        current: list[str] = []
        size = 0

        def flush():
            nonlocal current, size
            if current:
                pages.append("\n\n".join(current)); current = []; size = 0

        for paragraph in [p.strip() for p in re.split(r"\n\s*\n", block) if p.strip()]:
            chunks = [paragraph]
            if len(paragraph) > LIMIT:
                chunks, running = [], ""
                for sentence in sentences(paragraph):
                    if running and len(running) + 1 + len(sentence) > LIMIT:
                        chunks.append(running); running = sentence
                    else:
                        running = f"{running} {sentence}".strip()
                if running:
                    chunks.append(running)
            for chunk in chunks:
                extra = len(chunk) + (2 if current else 0)
                if current and size + extra > LIMIT:
                    flush()
                current.append(chunk); size += len(chunk) + (2 if len(current) > 1 else 0)
            # a paragraph that had to be split ends its page, so a split paragraph never shares a page with the next one
            if len(chunks) > 1:
                flush()
        flush()
    return pages


def expand():
    """[(step_number, step, [(beat_letter, beat, pages)])]"""
    out = []
    for number, step in enumerate(src.STEPS, 1):
        beats = []
        for index, beat in enumerate(step.beats):
            letter = "" if len(step.beats) == 1 else chr(ord("a") + index)
            beats.append((letter, beat, page_text(beat.text)))
        out.append((number, step, beats))
    return out


# ---- the C# the game reads ---------------------------------------------------------------------------------------------------------------------------------------------

def cs_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def build_cs(steps) -> str:
    lines = [
        "// <auto-generated> by tools/tutorial/build_lesson1.py from tools/tutorial/lesson1_source.py. Do not edit; change the source and run the script. </auto-generated>",
        "namespace L5R.Core;", "",
        "/// <summary>The words of lesson 1 (issue #935), paged to fit the tutorial's note column. One <see cref=\"TutorialBeat\"/> per beat of the build prompt; a note beat has one page per Continue,",
        "/// a move beat shows its last page with the \"To continue\" block and every earlier page as a note. TutorialLessonOne adds what each beat does to the table.</summary>",
        "internal sealed record TutorialBeat(string Step, int Number, string Letter, string Title, bool IsMove, string[] Pages, string Button, string Instruction, string Key);", "",
        "internal static class TutorialLessonOneText", "{",
        f"    public const int PageLimit = {LIMIT};",
        "    public static readonly TutorialBeat[] Beats =", "    [",
    ]
    for number, step, beats in steps:
        for letter, beat, pages in beats:
            is_move = isinstance(beat, src.Move)
            button = "" if is_move else beat.button
            instruction = beat.instruction if is_move else ""
            key = beat.key if is_move else ""
            page_list = ", ".join(cs_string(p) for p in pages)
            lines.append(f"        new({cs_string(step.id)}, {number}, {cs_string(letter)}, {cs_string(step.title)}, {str(is_move).lower()}, [{page_list}], {cs_string(button)}, {cs_string(instruction)}, {cs_string(key)}),")
    lines += ["    ];", "}", ""]
    return "\n".join(lines)


