#!/usr/bin/env python3
"""PreToolUse hook: blocks hand-edits to files this project generates by tooling.

Registered in .claude/settings.json under PreToolUse for Edit|Write|NotebookEdit.
Reads the standard PreToolUse JSON from stdin (tool_name, tool_input, cwd, ...:
see the "Claude Code hooks" section of the PR that added this file for the
research trail confirming these exact field names). For a target path matching
one of GENERATED below, it prints a hookSpecificOutput.permissionDecision: "deny"
JSON on stdout -- the documented mechanism that actually blocks a PreToolUse call,
honored on exit 0 -- and also exits 2 with the same reason on stderr as
defense-in-depth (exit 2 blocks unconditionally even if the JSON were somehow
ignored). Everything else prints nothing and exits 0, which is "no decision,
normal permission flow applies" -- this hook never overrides or duplicates
Rung 2's allow-list, it only ever adds a deny for these specific paths.

Regenerating instead of hand-editing matters because a hand edit either gets
silently clobbered on the next regeneration, or drifts from the packager's own
manifest/registration and breaks the published-count guard test.
"""
from __future__ import annotations

import fnmatch
import json
import os
from pathlib import Path
import sys

# (glob relative to the project root, how to regenerate it instead)
GENERATED = [
    ("docs/CARD_INVENTORY.xlsx",
     "python tools/content/build_card_inventory.py"),
    ("content/published/*.json",
     "the matching tools/content/package_*.py packager for that wave "
     "(package_published.py for lion-crane-*.json)"),
    ("content/catalogue-art-pack.json",
     "python tools/content/build_catalogue_art.py"),
    ("src/L5R.Client/Content/catalogue-art.json",
     "python tools/content/build_catalogue_art.py"),
]

EDIT_TOOLS = ("Edit", "Write", "NotebookEdit")
PATH_KEYS = ("file_path", "notebook_path")


def project_root():
    env = os.environ.get("CLAUDE_PROJECT_DIR")
    if env:
        return Path(env)
    return Path(__file__).resolve().parents[2]


def matching_rule(rel_posix):
    for pattern, regenerate in GENERATED:
        if fnmatch.fnmatch(rel_posix, pattern):
            return pattern, regenerate
    return None


def relative_target(root, raw_path):
    try:
        return Path(raw_path).resolve().relative_to(root.resolve())
    except (OSError, ValueError):
        return None  # outside the project entirely; not ours to police


def deny(reason):
    print(json.dumps({
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "deny",
            "permissionDecisionReason": reason,
        }
    }))
    print(reason, file=sys.stderr)
    sys.exit(2)


def check(payload, root):
    tool_name = payload.get("tool_name")
    if tool_name not in EDIT_TOOLS:
        return
    tool_input = payload.get("tool_input") or {}
    for key in PATH_KEYS:
        raw_path = tool_input.get(key)
        if not raw_path:
            continue
        rel = relative_target(root, raw_path)
        if rel is None:
            continue
        match = matching_rule(rel.as_posix())
        if match:
            pattern, regenerate = match
            deny(
                f"'{rel.as_posix()}' is generated by tooling (matches '{pattern}') and must not be "
                "hand-edited: a regeneration would silently clobber the edit, or it will drift from "
                "the packager's own manifest/registration and break the published-count guard. "
                f"Regenerate it instead with: {regenerate}"
            )


def main():
    try:
        payload = json.load(sys.stdin)
    except (ValueError, OSError):
        return 0  # never block on a malformed/empty hook payload
    check(payload, project_root())
    return 0


if __name__ == "__main__":
    sys.exit(main())
