using System.Text;

namespace L5R.Core;

public sealed record DeckEntry(string Name, int Count);

/// <summary>A player-built deck list: a `Legality:` label plus a flat, ordered sequence of
/// (count, name) entries. Matches the plain-text convention already used for this project's
/// legacy reference deck lists (see tools/content/import_sources.py's parse_deck) so files stay
/// compatible in both directions -- a legacy .txt deck list is already a valid Deck. Deliberately
/// carries no Stronghold/Clan/Dynasty-vs-Fate structure of its own: resolving what each entry
/// actually is requires a card pool this type does not have access to (content/deck-pool.json,
/// 1.2MB, generated by the Python content pipeline). Callers with that pool -- the deck builder,
/// match setup -- derive Stronghold/Clan/deck-type/canonical ordering from the entries themselves.</summary>
public sealed record Deck(string Legality, DeckEntry[] Entries);

public sealed record DeckLegalityViolation(string CardName, int Count, int Limit);
public sealed record DeckLegality(bool IsLegal, DeckLegalityViolation[] Violations);

/// <summary>Reads and writes the deck-list text format: one `Legality: value` line, then one
/// card per line as `COUNT NAME` (count omitted means 1). Comment lines (`#` or `//`) and blank
/// lines are ignored. Human-writable and diffable, so a deck can be hand-edited or dropped into
/// another player's local install.</summary>
public static class DeckFormat
{
    public static Deck Parse(string text)
    {
        string? legality = null;
        var entries = new List<DeckEntry>();
        foreach (var raw in text.Replace("\r\n", "\n").Split('\n'))
        {
            var line = raw.Trim();
            if (line.Length == 0 || line.StartsWith('#') || line.StartsWith("//")) continue;
            if (line.StartsWith("Legality:", StringComparison.OrdinalIgnoreCase))
            {
                legality = line[(line.IndexOf(':') + 1)..].Trim();
                continue;
            }
            var space = line.IndexOf(' ');
            if (space > 0 && int.TryParse(line[..space], out var count) && count > 0)
                entries.Add(new(line[(space + 1)..].Trim(), count));
            else
                entries.Add(new(line, 1));
        }
        if (legality is null) throw new FormatException("Deck must include a Legality: header line.");
        return new(legality, entries.ToArray());
    }

    public static string Write(Deck deck)
    {
        var text = new StringBuilder();
        text.AppendLine($"Legality: {deck.Legality}");
        text.AppendLine();
        foreach (var entry in deck.Entries)
            text.AppendLine(entry.Count == 1 ? entry.Name : $"{entry.Count} {entry.Name}");
        return text.ToString();
    }

    /// <summary>Soft check only: a deck may exceed these limits and still be built/saved/loaded
    /// (some Strongholds and cards are meant to break them; some players build illegal decks for
    /// fun). Stronghold/Bamboo Harvesters/Border Keep entries are ordinarily a single copy each,
    /// so they never trip a limit here even though this check has no way to exempt them by name.</summary>
    public static DeckLegality CheckLegality(Deck deck, Func<string, IReadOnlyList<string>> keywordsFor)
    {
        var violations = new List<DeckLegalityViolation>();
        foreach (var entry in deck.Entries)
        {
            var limit = keywordsFor(entry.Name).Contains("Unique", StringComparer.Ordinal) ? 1 : 3;
            if (entry.Count > limit) violations.Add(new(entry.Name, entry.Count, limit));
        }
        return new(violations.Count == 0, violations.ToArray());
    }
}
